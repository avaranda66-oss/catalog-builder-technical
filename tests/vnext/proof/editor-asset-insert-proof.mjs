import assert from 'node:assert/strict';
import { realpathSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { getDocument, OPS } from 'pdfjs-dist/legacy/build/pdf.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const output = resolve(root, 'scratch/asset-insert-proof');
await mkdir(output, { recursive: true });
const server = await createServer({ root, server: { host: '127.0.0.1', port: 5219, strictPort: true, fs: { allow: [root, realpathSync(resolve(root, 'node_modules'))] } }, logLevel: 'error' });
const file = { name: 'real-image.png', mimeType: 'image/png', buffer: await readFile(resolve(root, 'public/assets/vnext/w2c-replacement.png')) };
const state = (page) => page.evaluate(() => window.__ASSET_INSERT_PROOF__.state());
const selected = (page) => page.locator('[data-editor-object-id][data-selected="true"]');
const activate = async (page, action) => {
  const chooser = page.waitForEvent('filechooser');
  await page.locator(`[data-editor-action="${action}"]`).click();
  return chooser;
};
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ headless: Boolean(process.env.CI || process.env.ASSET_PROOF_HEADLESS) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  const url = 'http://127.0.0.1:5219/tests/vnext/proof/fixtures/editor-asset-insert-browser.html';
  await page.goto(url);
  await page.locator('[data-editor-action="add-image"]').waitFor();
  assert.deepEqual((await state(page)).document.assets, []);
  await page.evaluate(() => window.__ASSET_INSERT_PROOF__.hold());
  await (await activate(page, 'add-image')).setFiles(file);
  await page.getByRole('status').filter({ hasText: 'Enviando imagem…' }).waitFor();
  assert.equal((await state(page)).document.assets.length, 0);
  await page.waitForFunction(() => window.__ASSET_INSERT_PROOF__.state().uploadCount === 1);
  await page.evaluate(() => window.__ASSET_INSERT_PROOF__.release());
  await page.getByRole('status').filter({ hasText: 'Imagem adicionada.' }).waitFor();
  const inserted = await state(page);
  const image = inserted.document.pages[0].objects[0];
  assert.equal(await selected(page).getAttribute('data-editor-object-id'), image.id);
  assert.equal(image.assetId, inserted.document.assets[0].id);
  assert.equal(inserted.urls.length, 1);
  assert.equal(inserted.states[0][1].status, 'resolved');
  assert.equal(await page.locator('[data-editor-action="upload-image-input"]').inputValue(), '');
  assert(!JSON.stringify(inserted.document).match(/blob:|https?:|base64|bytes/));
  await page.locator('[data-editor-action="undo"]').click();
  assert.deepEqual((await state(page)).document.assets, []);
  assert.equal((await state(page)).document.pages[0].objects.length, 0);
  await page.locator('[data-editor-action="redo"]').click();
  assert.deepEqual((await state(page)).document, inserted.document);
  assert.equal((await state(page)).uploadCount, 1);
  await page.locator(`[data-editor-object-id="${image.id}"]`).click();
  await selected(page).scrollIntoViewIfNeeded();
  let box = await selected(page).boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 35, box.y + box.height / 2 + 20, { steps: 5 });
  await page.mouse.up();
  const moved = (await state(page)).document.pages[0].objects[0];
  assert.notDeepEqual(moved.frame, image.frame);
  box = await page.locator('[data-resize-handle="se"]').boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + 30, box.y + 25, { steps: 5 });
  await page.mouse.up();
  const resized = (await state(page)).document.pages[0].objects[0];
  assert(resized.frame.widthMm > moved.frame.widthMm);
  await page.locator('[data-editor-action="save"]').click();
  await page.waitForFunction(() => !window.__ASSET_INSERT_PROOF__.state().dirty);
  const saved = (await state(page)).saved;
  assert.deepEqual(saved.pages[0].objects[0], resized);
  assert(!JSON.stringify(saved).match(/blob:|https?:|base64|bytes/));
  await page.getByRole('button', { name: 'Abrir outro catálogo', exact: true }).click();
  await page.waitForFunction(() => window.__ASSET_INSERT_PROOF__.state().document.id === window.__ASSET_INSERT_PROOF__.otherId);
  await page.getByRole('button', { name: 'Reabrir catálogo original', exact: true }).click();
  await page.waitForFunction(() => window.__ASSET_INSERT_PROOF__.state().document.id === window.__ASSET_INSERT_PROOF__.primaryId);
  assert.deepEqual((await state(page)).document, saved);
  await page.locator(`img[data-asset-id="${image.assetId}"]`).waitFor();
  assert(await page.locator(`img[data-asset-id="${image.assetId}"]`).evaluate((node) => node.complete && node.naturalWidth > 0));
  await page.locator(`[data-editor-object-id="${image.id}"]`).click();
  await (await activate(page, 'replace-image')).setFiles(file);
  await page.getByRole('status').filter({ hasText: 'Imagem substituída.' }).waitFor();
  const replaced = (await state(page)).document.pages[0].objects[0];
  assert.notEqual(replaced.assetId, image.assetId);
  assert.deepEqual(replaced.frame, resized.frame);
  assert.equal((await state(page)).uploadCount, 2);
  await (await activate(page, 'upload-image')).setFiles(file);
  await page.waitForFunction(() => window.__ASSET_INSERT_PROOF__.state().document.assets.length === 3);
  assert.equal((await state(page)).uploadCount, 3);
  const inspectorChooser = page.waitForEvent('filechooser');
  await page.locator('.vnext-inspector-action').filter({ hasText: 'Substituir imagem' }).click();
  await (await inspectorChooser).setFiles(file);
  await page.waitForFunction(() => window.__ASSET_INSERT_PROOF__.state().document.assets.length === 4);
  assert.equal((await state(page)).uploadCount, 4);
  await page.screenshot({ path: resolve(output, 'desktop.png'), fullPage: true });
  const beforePublication = (await state(page)).document;
  await page.getByRole('button', { name: 'Publicar prova', exact: true }).click();
  await page.locator('[data-publication] img').waitFor();
  const report = await page.evaluate(() => window.__ASSET_INSERT_PROOF__.publication());
  assert.deepEqual(report.diagnostics.filter((d) => d.severity === 'ERROR'), []);
  assert.equal(await page.locator('input, [data-editor-action], [data-editor-overlay]').count(), 0);
  await page.pdf({ path: resolve(output, 'inserted-image.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true });
  const pdf = await getDocument({ data: new Uint8Array(await readFile(resolve(output, 'inserted-image.pdf'))), isEvalSupported: false }).promise;
  const ops = await (await pdf.getPage(1)).getOperatorList();
  assert(ops.fnArray.some((op) => [OPS.paintImageXObject, OPS.paintInlineImageXObject, OPS.paintImageXObjectRepeat].includes(op)), 'PDF must contain the uploaded raster image');
  assert.deepEqual((await state(page)).document, beforePublication);
  const mobile = [];
  for (const width of [320, 360, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(url);
    await page.locator('[data-editor-action="add-image"]').waitFor();
    await page.evaluate(() => window.__ASSET_INSERT_PROOF__.hold());
    await (await activate(page, 'add-image')).setFiles(file);
    await page.getByRole('status').filter({ hasText: 'Enviando imagem…' }).waitFor();
    await page.getByRole('status').scrollIntoViewIfNeeded();
    assert(await page.getByRole('status').isVisible());
    await page.waitForFunction(() => window.__ASSET_INSERT_PROOF__.state().uploadCount === 1);
    await page.evaluate(() => window.__ASSET_INSERT_PROOF__.release());
    await page.getByRole('status').filter({ hasText: 'Imagem adicionada.' }).waitFor();
    assert.equal(await selected(page).count(), 1);
    await selected(page).scrollIntoViewIfNeeded();
    assert.equal(await page.locator('[data-resize-handle="se"]').count(), 1);
    await page.locator('[data-inspector-field="x"]').fill('25');
    await page.locator('[data-inspector-field="x"]').press('Enter');
    assert.equal((await state(page)).document.pages[0].objects[0].frame.xMm, 25);
    const scrollWidth = await page.evaluate(() => document.documentElement.scrollWidth);
    assert.equal(scrollWidth, width);
    mobile.push({ width, scrollWidth, selected: true, picker: true, moveInspector: true, resizeHandle: true });
    await page.screenshot({ path: resolve(output, `mobile-${width}.png`), fullPage: true });
  }
  assert.deepEqual(errors, []);
  const result = { status: 'PASS', browser: browser.version(), visible: !process.env.CI && !process.env.ASSET_PROOF_HEADLESS, controlledPersistence: true, productionSupabaseE2E: false, uploadCountDesktop: 4, toolbarAndInspectorReplacement: true, exactSaveReopen: true, pdfImage: true, mobile, errors };
  await writeFile(resolve(output, 'report.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally {
  await browser?.close();
  await server.close();
}
